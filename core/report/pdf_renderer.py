async def render_pdf(report: ReportOutput) -> bytes:
    """Render report to PDF bytes. Runs WeasyPrint in a thread pool."""
    html = _build_html(report)
    loop = asyncio.get_event_loop()
    pdf_bytes = await loop.run_in_executor(None, partial(_weasyprint_render, html))
    return pdf_bytes


def _build_html(report: ReportOutput) -> str:
    score = report.resolution_clarity_score
    if score >= 70:
        score_color = "#166534"
    elif score >= 50:
        score_color = "#92400e"
    else:
        score_color = "#991b1b"

    findings_html = ""
    for f in report.findings:
        txt_color, bg_color = SEVERITY_COLORS[f.severity]
        badge = (
            f'<span class="badge" style="background:{bg_color};color:{txt_color}">'
            f"{f.severity.value.upper()}</span>"
        )
        cat = f.category.value.replace("_", " ").title()
        evidence_html = ""
        if f.evidence:
            items = "".join(f"<li>{e}</li>" for e in f.evidence[:5])
            evidence_html = f'<div class="evidence"><ul>{items}</ul></div>'

        findings_html += f"""
        <div class="finding">
          <div class="finding-header">{badge}<span class="cat-label">{cat}</span></div>
          <div class="finding-desc">{f.description}</div>
          <div class="label">Affected clause</div>
          <div class="clause-block">{f.affected_clause}</div>
          <div class="label">Suggested rewrite</div>
          <div class="rewrite-block">{f.rewrite}</div>
          {evidence_html}
        </div>
        """

    rewritten_section = ""
    if report.rewritten_contract:
        rewritten_section = f"""
        <h2>Composite Rewritten Contract</h2>
        <div class="rewritten">{report.rewritten_contract}</div>
        """

    return HTML_TEMPLATE.format(
        report_id=str(report.id),
        created_at=report.created_at.strftime("%Y-%m-%d %H:%M UTC"),
        score=score,
        score_label=report.score_label,
        score_color=score_color,
        critical=report.critical_count,
        high=report.high_count,
        medium=report.medium_count,
        low=report.low_count,
        total=len(report.findings),
        findings_html=findings_html,
        rewritten_section=rewritten_section,
        duration=f"{report.audit_duration_seconds:.1f}",
        model=report.model_version,
    )


def _weasyprint_render(html: str) -> bytes:
    from weasyprint import HTML

    return HTML(string=html).write_pdf()
