"""
core/report/pdf_renderer.py

Renders a ReportOutput to a PDF binary using WeasyPrint + Jinja2.

The HTML template is inline here for portability — no external
template files to manage. The PDF is returned as bytes.
"""

from __future__ import annotations

import asyncio
from functools import partial

from api.schemas.report import ReportOutput, Severity

